import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { test } from 'node:test';
import {
  captionsFromCues,
  cueText,
  languageOf,
  pickXTrack,
  postTitle,
  xCaptionsShown,
  xVideoId,
  type XTextTrack,
} from '../src/x-video.ts';

const fixture = JSON.parse(readFileSync(new URL('./fixtures/x-video-tracks.json', import.meta.url), 'utf8'));

const track = (fields: Partial<XTextTrack>): XTextTrack => ({ kind: 'subtitles', label: 'English', language: 'en', mode: 'disabled', ...fields });

test('pickXTrack: the only track of a video, whatever case X writes its language in', () => {
  assert.deepEqual(pickXTrack(fixture.autoGenerated.tracks, 'ja'), { index: 0, track: { languageCode: 'en', kind: 'asr' } });
  assert.deepEqual(pickXTrack(fixture.uploadedUpperCaseLanguage.tracks, 'ja'), { index: 0, track: { languageCode: 'en' } });
});

test("pickXTrack: never X's copy of the cues it shows (kind captions, no language)", () => {
  assert.deepEqual(pickXTrack(fixture.uploadedWithCcOn.tracks, 'ja'), { index: 0, track: { languageCode: 'en' } });
  assert.equal(pickXTrack([fixture.uploadedWithCcOn.tracks[1]], 'ja'), null);
});

test('pickXTrack: skips tracks already in the target language, and tracks without a language', () => {
  assert.equal(pickXTrack([track({ language: 'ja' })], 'ja'), null);
  assert.equal(pickXTrack([track({ language: '' }), track({ language: 'not a language!' })], 'ja'), null);
  assert.deepEqual(pickXTrack([track({ language: 'ja', mode: 'hidden' }), track({ language: 'en' })], 'ja'), {
    index: 1,
    track: { languageCode: 'en' },
  });
  // Translating into English, an English track is skipped
  assert.equal(pickXTrack(fixture.autoGenerated.tracks, 'en-US'), null);
});

test('pickXTrack: the track X has loaded first, then the creator’s own before an auto-generated one', () => {
  const auto = track({ label: 'en (auto-generated)' });
  const own = track({ label: 'Talk.es.srt', language: 'es' });
  assert.equal(pickXTrack([auto, own], 'ja')?.index, 1);
  assert.equal(pickXTrack([own, { ...auto, mode: 'hidden' }], 'ja')?.index, 1);
  assert.equal(pickXTrack([auto, { ...auto, language: 'fr' }], 'ja')?.index, 0);
});

test('languageOf: a BCP 47 code, or null', () => {
  assert.equal(languageOf('EN'), 'en');
  assert.equal(languageOf('en-us'), 'en-US');
  assert.equal(languageOf(' '), null);
  assert.equal(languageOf('english please'), null);
});

test('xCaptionsShown: while X shows its captions, a track is showing', () => {
  assert.equal(xCaptionsShown(fixture.uploadedWithCcOn.tracks), true);
  assert.equal(xCaptionsShown(fixture.autoGenerated.tracks), false);
  assert.equal(xCaptionsShown([]), false);
});

test("cueText: drops WebVTT's markup and X's word timings, reads entities, and joins the lines", () => {
  assert.equal(cueText(fixture.autoGenerated.cues[0].text), 'Let me tell you what this is not');
  assert.equal(cueText(fixture.uploadedFromOneHour.cues[0].text), 'Welcome to Max Power.');
  assert.equal(cueText('<v Roger>Hi</v> <c.yellow>there</c>\n<i>Tom &amp; Jerry</i> &lt;3 &#x2764; &#65;&nbsp;b'), 'Hi there Tom & Jerry <3 ❤ A b');
  assert.equal(cueText('<00:00:01.000>one <00:00:02.000>two'), 'one two');
  assert.equal(cueText('&bogus; &#xFFFFFFF;'), '&bogus; &#xFFFFFFF;');
});

test('captionsFromCues: the lines of an auto-generated track, in order', () => {
  assert.deepEqual(captionsFromCues(fixture.autoGenerated.cues, fixture.autoGenerated.duration), [
    { startTime: 0.18, endTime: 1.841, text: 'Let me tell you what this is not' },
    { startTime: 2.061, endTime: 3.121, text: 'as far as we can tell' },
    { startTime: 3.201, endTime: 6.422, text: 'and this is coordinating with private sector' },
    { startTime: 6.862, endTime: 9.443, text: 'using our, government technology and' },
  ]);
});

test('captionsFromCues: sorts, drops empty cues, and cuts a line off where the next one starts', () => {
  const cues = [
    { startTime: 5, endTime: 9, text: 'second' },
    { startTime: 1, endTime: 6, text: 'first' },
    { startTime: 3, endTime: 4, text: '<b> </b>' },
    { startTime: 7, endTime: 7, text: 'no time on screen' },
  ];
  assert.deepEqual(captionsFromCues(cues, NaN), [
    { startTime: 1, endTime: 5, text: 'first' },
    { startTime: 5, endTime: 9, text: 'second' },
  ]);
});

test('captionsFromCues: cues timed past the end of the video are dropped (X shows nothing for them either)', () => {
  assert.deepEqual(captionsFromCues(fixture.uploadedFromOneHour.cues, fixture.uploadedFromOneHour.duration), []);
  // While the duration is unknown, nothing is dropped for it
  assert.equal(captionsFromCues(fixture.uploadedFromOneHour.cues, NaN).length, 3);
  assert.equal(captionsFromCues(fixture.uploadedWithCcOn.cues, NaN).length, 3);
});

test("xVideoId: the media id in the poster, else the post's id, else null", () => {
  assert.equal(
    xVideoId('https://pbs.twimg.com/amplify_video_thumb/2119833138889158657/img/tBwXGqHF9Nt0cudp.jpg', null),
    'x:2119833138889158657'
  );
  assert.equal(xVideoId('https://pbs.twimg.com/ext_tw_video_thumb/1813709208858353664/pu/img/a.jpg', null), 'x:1813709208858353664');
  // A poster the creator chose holds no media id
  assert.equal(xVideoId('https://pbs.twimg.com/media/HXRLj6bW0AAxO8n.jpg', '/NASA/status/2119136607009734978'), 'x:post:2119136607009734978');
  assert.equal(xVideoId('https://pbs.twimg.com/media/HXRLj6bW0AAxO8n.jpg', 'https://x.com/NASA/status/2119136607009734978/video/1'), 'x:post:2119136607009734978');
  assert.equal(xVideoId('', null), null);
  assert.equal(xVideoId('https://example.com/amplify_video_thumb/1/img.jpg', '/NASA'), null);
});

test('postTitle: the post text on one line, cut to its length', () => {
  assert.equal(postTitle('Do you want to be an astronaut?\n\nApplications are now open.'), 'Do you want to be an astronaut? Applications are now open.');
  assert.equal(postTitle('  '), undefined);
  assert.equal(postTitle(null), undefined);
  assert.equal(postTitle('abcdef', 3), 'abc…');
  // Characters, not UTF-16 halves
  assert.equal(postTitle('🚀🚀🚀🚀', 2), '🚀🚀…');
});
